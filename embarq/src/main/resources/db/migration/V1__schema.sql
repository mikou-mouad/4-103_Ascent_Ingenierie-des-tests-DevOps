create table traversee (
    id          bigint generated by default as identity primary key,
    depart      varchar(60)  not null,
    arrivee     varchar(60)  not null,
    date_heure  timestamp    not null,
    navire      varchar(60)  not null,
    capacite    integer      not null check (capacite > 0)
);

create table reservation (
    id            bigint generated by default as identity primary key,
    reference     varchar(20)   not null unique,
    traversee_id  bigint        not null references traversee (id),
    nom           varchar(120)  not null,
    email         varchar(200)  not null,
    adultes       integer       not null,
    enfants       integer       not null,
    velos         integer       not null,
    montant       numeric(8, 2) not null,
    statut        varchar(20)   not null,
    cree_le       timestamp     not null
);

create index reservation_traversee on reservation (traversee_id);
